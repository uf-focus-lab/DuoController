#!/usr/bin/env python3
"""Write board/bringup.md: continuity table, rail short checks, power-up steps.

    python3 tools/gen_bringup.py [--quiet]

Generated from board/netlist.py (also run by board/layout.py).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BOARD = os.path.join(HERE, "..", "board")
OUT = os.path.join(BOARD, "bringup.md")
sys.dont_write_bytecode = True
sys.path.insert(0, BOARD)

RAILS = ("+5V", "+3V3", "GND")


def natkey(s):
    import re
    return [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", s)]


def main(quiet=False):
    import netlist as NL
    teensy = {net: pin for pin, net in NL.PARTS["U1"][5].items()}
    out = ["# FoveaCam Duo Driver: bring-up checklist", "",
           "GENERATED by tools/gen_bringup.py from board/netlist.py; do not edit.", "",
           "Bare board first (no Teensy), then with the Teensy fitted.  Tick each row.", "",
           "## 1. Rail isolation (bare board, multimeter on resistance)", "",
           "| Between | Expect |", "|---|---|"]
    for i, a in enumerate(RAILS):
        for b in RAILS[i + 1:]:
            out.append(f"| {a} and {b} | open (no short) |")
    out += ["", "Probe points: +5V = J_UART1 pin 1, +3V3 = J_UART1 pin 2, "
            "GND = J_UART1 pin 3.", "",
            "## 2. Continuity, connector pin to Teensy pin", "",
            "| Connector | Pin | Net | Teensy pin | OK |", "|---|---|---|---|---|"]
    for ref in sorted(NL.PARTS, key=natkey):
        if not ref.startswith("J_"):          # connectors only (no Teensy, caps)
            continue
        pins = NL.PARTS[ref][5]
        for num in sorted(pins, key=natkey):
            net = pins[num]
            tp = teensy.get(net, "")
            if net == "+5V":
                tp = "VIN"
            elif net == "+3V3":
                tp = "3V3"
            elif net == "GND":
                tp = "GND"
            out.append(f"| {ref} | {num} | {net} | {tp} | [ ] |")
        nc = [n for n in sorted(NL.PARTS[ref][5] and _all_pins(ref), key=natkey)
              if n not in pins]
        if nc:
            out.append(f"| {ref} | {', '.join(nc)} | not connected (check open to "
                       f"GND) | | [ ] |")
    out += ["", "## 3. Power-up", "",
            "1. Power: +5V comes only from the Teensy's USB through its VIN pin "
            "(VIN and VUSB bridged on the Teensy, as shipped). J_PWR1-3 are 5 V "
            "OUTPUTS for cooling fans, never feed power into them (owner "
            "2026-10-07; budget in specs.md 4: about 100 mA per fan on USB 2.0). "
            "The optional capacitors (VARIANT=caps) exceed the USB 2.0 inrush "
            "limit of 10 uF; fit them only if fan noise needs them.",
            "2. Flash the V0.1 firmware (pins as in board/pins.h, firmware notes "
            "at its end) into the Teensy before it goes onto this board: the V0.1 "
            "pin map differs from V0.0 on almost every pin.",
            "3. Fit the Teensy (socket strips on the back, USB end west, at the USB "
            "icon). Repeat section 1 (+5V to GND and +3V3 to GND must not read as "
            "a short).",
            "4. Power up from USB with no MEMS driver, camera or fan connected.",
            "5. Measure +5V (J_UART1 pin 1, J_PWR1-3 pin 1) and +3V3 (J_UART1 pin 2) "
            "against GND (J_UART1 pin 3).",
            "6. Check that MEMS_EN (J_SPI1 / J_SPI2 pin 5, Teensy pin 6) reads LOW "
            "from reset until the firmware enables the drivers (pin 6 is pulled "
            "down during reset and kept by its keeper; the firmware drives it LOW "
            "first, pins.h).",
            "7. Load a sketch that toggles each output in board/pins.h and check it "
            "at the connector pins of section 2 (MEMS_EN, FCLK, CSn, SCLKn, MOSIn; "
            "CAMn_IN); with INPUT_PULLUP on CAMn_OUT and CAMn_L2, shorting the "
            "connector pin to GND must read LOW. Leave CAMn_L3 as inputs.",
            "8. Connect one MEMS driver to J_SPI1 (DRV1), check it powers from +5V, "
            "then the second on J_SPI2 (DRV2). Bring-up order per the Mirrorcle "
            "guide p27: DAC init, Vbias, FCLK, then MEMS_EN high.",
            "9. Connect the cameras (J_CAM0..2): FLIR GPIO cable pin n to J_CAMn pin n. "
            "Pin 1 (Line3) is wired to a Teensy pin: never configure the camera to "
            "output VAUX (8-24 V) on Line3. Connect opto GND "
            "(blue, pin 5) before any signal (FLIR warning).", ""]
    text = "\n".join(out)
    old = open(OUT).read() if os.path.exists(OUT) else None
    if text != old:
        with open(OUT, "w") as f:
            f.write(text)
    if not quiet:
        print(f"bringup.md ok{'' if text != old else ' (unchanged)'}")


def _all_pins(ref):
    """All pad numbers of ref's symbol (from the schematic emitter's libraries)."""
    import schematic
    return list(schematic.pin_table()[ref])


if __name__ == "__main__":
    main("--quiet" in sys.argv[1:])
