#!/usr/bin/env python3
"""Harvest the routing of a board file into board/routes.py (pad-relative).

For hand edits: route in KiCad on a copy of the generated board, then

    python3 tools/harvest_routes.py path/to/edited.kicad_pcb   # rewrites board/routes.py
    python3 tools/harvest_routes.py --check                    # generated board -> routes.py unchanged?
    python3 tools/harvest_routes.py BOARD -o FILE              # write elsewhere

Every track and via is turned into the lib/routing.py vocabulary: each
route starts on a pad (or a named junction of its net), walks segment by
segment as relative moves, places vias where it changes layer, and ends on
a pad, a junction or a free end.  Free-standing vias become VIAS.  The
result depends only on the copper geometry (not on item order or segment
direction), so harvesting the generated board reproduces routes.py byte for
byte.  Anything that cannot be anchored (copper reachable from no pad) is
listed and makes the tool exit 1; nothing is guessed.  Arcs are not
supported (reported).

Exit 0 with one line on success; --check exits 1 when routes.py would change.
"""
import argparse
import math
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
sys.dont_write_bytecode = True
sys.path.insert(0, os.path.join(ROOT, "lib"))
import pcbnew  # noqa: E402

from routing import W_PWR, W_SIG  # noqa: E402

BOARD = os.path.join(ROOT, "board", "FoveaCamDuo-PCB.kicad_pcb")
OUT = os.path.join(ROOT, "board", "routes.py")
LNAME = {pcbnew.F_Cu: "F", pcbnew.B_Cu: "B"}
WNAME = {int(round(W_SIG * 1e6)): "W_SIG", int(round(W_PWR * 1e6)): "W_PWR"}

HEADER = '''"""Routing of the FoveaCam Duo Driver, pad-relative (lib/routing.py).

GENERATED by tools/harvest_routes.py from a board file; edit by hand or
re-harvest (layout.py builds from this file either way).  Routes start on a
pad, move in mm (dx, dy; y down) and end on a pad; F / B after a VIA changes
the copper layer.  Track widths: W_SIG
0.254 mm, W_PWR 0.508 mm.
"""
from routing import B, F, VIA, W_PWR, W_SIG, at, mark, pad  # noqa: F401

ROUTES = {
'''


def natkey(s):
    return [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", s)]


def mm(v):
    s = f"{v / 1e6:.6f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def harvest(path):
    b = pcbnew.LoadBoard(path)
    problems = []
    pads = [p for f in b.GetFootprints() for p in f.Pads()]
    segs, vias = {}, {}
    for t in b.GetTracks():
        c = t.GetClass()
        if c == "PCB_ARC":
            problems.append(f"arc on {t.GetNetname()} at {mm(t.GetStart().x)}, "
                            f"{mm(t.GetStart().y)}: arcs are not supported")
        elif c == "PCB_VIA":
            p = t.GetPosition()
            vias.setdefault(t.GetNetname(), {})[(p.x, p.y)] = t
        else:
            a, e = t.GetStart(), t.GetEnd()
            segs.setdefault(t.GetNetname(), []).append(
                ((a.x, a.y), (e.x, e.y), t.GetLayer(), t.GetWidth()))
    routes, standalone = {}, []
    for net in sorted(set(segs) | set(vias), key=natkey):
        edges = segs.get(net, [])
        nv = vias.get(net, {})
        adj = {}
        for i, (a, e, _, _) in enumerate(edges):
            adj.setdefault(a, []).append(i)
            adj.setdefault(e, []).append(i)
        for xy, v in sorted(nv.items()):
            if xy not in adj:
                standalone.append((net, xy, v.GetIsFree()))
        netpads = [p for p in pads if p.GetNetname() == net]

        def pad_at(xy, layer):
            hits = [p for p in netpads if p.IsOnLayer(layer)
                    and p.HitTest(pcbnew.VECTOR2I(*xy), 0)]
            if not hits:
                return None
            hits.sort(key=lambda p: (math.hypot(p.GetPosition().x - xy[0],
                                                p.GetPosition().y - xy[1]),
                                     natkey(p.GetParentFootprint().GetReference()),
                                     natkey(p.GetNumber())))
            return hits[0]

        used, marks, placed, out = set(), {}, set(), []

        def deg(n):
            return len(adj[n])

        def other(i, n):
            a, e = edges[i][0], edges[i][1]
            return e if a == n else a

        def node_pad(n):
            return next((pad_at(n, edges[i][2]) for i in adj[n]
                         if pad_at(n, edges[i][2])), None)

        def starts():
            c = []
            for n in adj:
                free = [i for i in adj[n] if i not in used]
                if not free:
                    continue
                p = node_pad(n)
                if n in marks:
                    c.append((1, list(marks).index(n), [], n))
                elif p is not None:
                    key = (natkey(p.GetParentFootprint().GetReference()), natkey(p.GetNumber()))
                    c.append((0 if deg(n) != 2 else 2, key, [], n))
            return sorted(c)

        def anchor_tok(n, layer):
            p = pad_at(n, layer)
            if p is not None:
                c = p.GetPosition()
                ref = p.GetParentFootprint().GetReference()
                if (c.x, c.y) == n:
                    return f'pad("{ref}", "{p.GetNumber()}")'
                return (f'pad("{ref}", "{p.GetNumber()}", {mm(n[0] - c.x)}, '
                        f'{mm(n[1] - c.y)})')
            if n in marks:
                return f'at("{marks[n]}")'
            return None

        while True:
            st = starts()
            if not st:
                break
            n = st[0][3]
            free = sorted((i for i in adj[n] if i not in used),
                          key=lambda i: (LNAME.get(edges[i][2], "?"), edges[i][3],
                                         round(math.atan2(other(i, n)[1] - n[1],
                                                          other(i, n)[0] - n[0]), 9)))
            i = free[0]
            layer, width = edges[i][2], edges[i][3]
            toks = [anchor_tok(n, layer)]
            if n in nv and n not in placed:
                toks.append("VIA")
                placed.add(n)
            cur = n
            while True:
                used.add(i)
                if edges[i][2] != layer:
                    layer = edges[i][2]
                    toks.append(LNAME[layer])
                nxt = other(i, cur)
                tok = anchor_tok(nxt, layer)
                toks.append(tok or f"({mm(nxt[0] - cur[0])}, {mm(nxt[1] - cur[1])})")
                cur = nxt
                rest = [j for j in adj[cur] if j not in used]
                # continue through a plain bend, a via, or a pad; stop at a
                # junction, a width change or a layer change without a via
                term = (deg(cur) != 2 or not rest or edges[rest[0]][3] != width
                        or (edges[rest[0]][2] != layer and cur not in nv))
                if term and deg(cur) > 2 and cur not in marks and node_pad(cur) is None:
                    marks[cur] = f"{net}.{len(marks) + 1}"
                    toks.append(f'mark("{marks[cur]}")')
                if cur in nv and cur not in placed:
                    toks.append("VIA")
                    placed.add(cur)
                if term:
                    break
                i = rest[0]
            out.append((LNAME[edges[free[0]][2]], WNAME.get(width, mm(width)), toks))
        left = [e for k, e in enumerate(edges) if k not in used]
        for a, e, lay, _ in left:
            problems.append(f"{net}: segment {mm(a[0])},{mm(a[1])} -> {mm(e[0])},{mm(e[1])} "
                            f"on {LNAME.get(lay, lay)} reaches no pad")
        if out:
            routes[net] = out
    for net, xy, free in standalone:
        if not free:
            problems.append(f"{net}: via at {mm(xy[0])},{mm(xy[1])} touches no track "
                            "but is not marked free")
    return routes, standalone, problems


def render(routes, standalone):
    lines = [HEADER]
    for net, paths in routes.items():
        lines.append(f'    "{net}": [\n')
        for lay, w, toks in paths:
            cur = f"        ({lay}, {w}, ["
            for k, t in enumerate(toks):
                piece = t + (", " if k < len(toks) - 1 else "]),")
                if len(cur) + len(piece.rstrip()) > 99:
                    lines.append(cur.rstrip() + "\n")
                    cur = "            "
                cur += piece
            lines.append(cur.rstrip() + "\n")
        lines.append("    ],\n")
    lines.append("}\n\n# free-standing (stitching) vias: (net, x, y), board frame\nVIAS = [\n")
    for net, xy, _ in standalone:
        lines.append(f'    ("{net}", {mm(xy[0])}, {mm(xy[1])}),\n')
    lines.append("]\n")
    return "".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("board", nargs="?", default=BOARD)
    ap.add_argument("-o", "--out", default=OUT)
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the harvest differs from the output file")
    a = ap.parse_args()
    routes, standalone, problems = harvest(a.board)
    if problems:
        print("harvest: cannot anchor / unsupported:", *problems, sep="\n  ")
        sys.exit(1)
    text = render(routes, standalone)
    old = open(a.out).read() if os.path.exists(a.out) else None
    if a.check:
        if text != old:
            print(f"harvest: {a.out} differs from the routing in {a.board}")
            sys.exit(1)
        print(f"harvest ok: routes.py matches the board ({len(routes)} nets)")
        return
    if text != old:
        with open(a.out, "w") as f:
            f.write(text)
    print(f"harvest ok: {len(routes)} nets, {len(standalone)} stitching vias -> {a.out}"
          f"{'' if text != old else ' (unchanged)'}")


if __name__ == "__main__":
    main()
