#!/usr/bin/env python3
"""Write board/pins.h: the Teensy 4.0 pin number of every signal net.

    python3 tools/gen_pins.py [--quiet]

Generated from board/netlist.py (also run by board/layout.py).  Plain C with
an include guard, for the firmware (#include "pins.h").  The header names
the generator and a hash of netlist.py rather than a git commit, so the file
only changes when the pin map does (a commit hash would change it on every
commit).
"""
import hashlib
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
BOARD = os.path.join(HERE, "..", "board")
OUT = os.path.join(BOARD, "pins.h")
sys.dont_write_bytecode = True
sys.path.insert(0, BOARD)


def macro(net):
    m = re.match(r"Net-\((\w+)-Pin_(\d+)\)", net)
    if m:                                    # unnamed net: the header pin
        return f"{m.group(1).replace('J_', '')}_PIN{m.group(2)}"
    return re.sub(r"\W", "_", net)


def main(quiet=False):
    import netlist as NL
    src = open(os.path.join(BOARD, "netlist.py"), "rb").read()
    digest = hashlib.sha1(src).hexdigest()[:12]
    pins = NL.PARTS["U1"][5]
    rows = []
    for num, net in sorted(pins.items(), key=lambda kv: (not kv[0].isdigit(),
                                                        int(kv[0]) if kv[0].isdigit() else 0)):
        if not num.isdigit() or net in ("GND", "+3V3", "+5V"):
            continue
        if int(num) > 23:                    # 24..26 are 3V3 / GND / VIN pads
            continue
        others = sorted(f"{r}.{p}" for r, (_, _, _, _, _, pm) in NL.PARTS.items()
                        if r != "U1" for p, n in pm.items() if n == net)
        rows.append((macro(net), int(num), net, others))
    w = max(len(r[0]) for r in rows) + 5      # "PIN_" + name + a space
    out = ["/* FoveaCam Duo Driver: Teensy 4.0 pin map.",
           " *",
           " * GENERATED by tools/gen_pins.py from board/netlist.py "
           f"(sha1 {digest}); do not edit.",
           " * Numbers are Teensy digital pin numbers (pinMode / digitalWrite).",
           " */",
           "#ifndef FOVEACAM_DUO_PINS_H",
           "#define FOVEACAM_DUO_PINS_H",
           ""]
    for name, num, net, others in rows:
        out.append(f"#define {('PIN_' + name).ljust(w)}{num:>2}   /* {net}: "
                   f"{', '.join(others)} */")
    level = getattr(NL, "STROBE_ACTIVE_LEVEL", None)
    if level:
        out += ["",
                "/* Level read on PIN_CAMn_OUT while camera n exposes: the camera's",
                " * opto output (open collector) pulls the line LOW against the",
                " * Teensy's internal pull-up (INPUT_PULLUP); no receiver on the board. */",
                f"#define STROBE_ACTIVE_LEVEL {level}"]
    notes = getattr(NL, "FIRMWARE_NOTES", None)
    if notes:
        out += ["", "/* Firmware notes (board/netlist.py FIRMWARE_NOTES):"]
        out += [" * " + n for n in notes]
        out += [" */"]
    spare = [p for p in range(24) if str(p) not in pins]
    if spare:
        out += ["", "/* Teensy pins not connected on this board: "
                + ", ".join(map(str, spare)) + " */"]
    out += ["", "#endif /* FOVEACAM_DUO_PINS_H */", ""]
    text = "\n".join(out)
    old = open(OUT).read() if os.path.exists(OUT) else None
    if text != old:
        with open(OUT, "w") as f:
            f.write(text)
    if not quiet:
        print(f"pins.h ok: {len(rows)} pins{'' if text != old else ' (unchanged)'}")


if __name__ == "__main__":
    main("--quiet" in sys.argv[1:])
